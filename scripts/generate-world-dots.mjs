/**
 * Builds the dot-matrix land mask used by the supply-network map.
 *
 * Source: Natural Earth 1:110m land (public domain), as packaged by the
 * `world-atlas` npm package (land-110m.json, TopoJSON). The dataset is NOT a
 * dependency of the app: the mask is generated once and committed as
 * `src/lib/geo/world-dots.ts`.
 *
 * Usage:  node scripts/generate-world-dots.mjs <path-to>/land-110m.json
 */
import { readFileSync, writeFileSync, mkdirSync } from "node:fs";
import { dirname, resolve } from "node:path";
import { fileURLToPath } from "node:url";

const source = process.argv[2];
if (!source) {
  console.error("Pass the path to world-atlas/land-110m.json");
  process.exit(1);
}

const STEP = 2; // degrees per cell
const LON_MIN = -180;
const LON_MAX = 180;
const LAT_MAX = 78;
const LAT_MIN = -56;

const topology = JSON.parse(readFileSync(source, "utf8"));
const { scale, translate } = topology.transform;

// Decode delta-encoded, quantised arcs into lon/lat coordinates.
const arcs = topology.arcs.map((arc) => {
  let x = 0;
  let y = 0;
  return arc.map(([dx, dy]) => {
    x += dx;
    y += dy;
    return [x * scale[0] + translate[0], y * scale[1] + translate[1]];
  });
});

const ringFromArcs = (indexes) => {
  const ring = [];
  indexes.forEach((index) => {
    const points = index < 0 ? [...arcs[~index]].reverse() : arcs[index];
    points.forEach((point, i) => {
      if (i > 0 || ring.length === 0) ring.push(point);
    });
  });
  return ring;
};

const rings = [];
const collect = (geometry) => {
  if (geometry.type === "GeometryCollection") geometry.geometries.forEach(collect);
  else if (geometry.type === "Polygon") geometry.arcs.forEach((r) => rings.push(ringFromArcs(r)));
  else if (geometry.type === "MultiPolygon") geometry.arcs.forEach((p) => p.forEach((r) => rings.push(ringFromArcs(r))));
};
collect(topology.objects.land);

// Bounding boxes make the even-odd test fast enough for a one-off script.
const boxed = rings.map((ring) => {
  let minX = Infinity;
  let maxX = -Infinity;
  let minY = Infinity;
  let maxY = -Infinity;
  ring.forEach(([x, y]) => {
    minX = Math.min(minX, x);
    maxX = Math.max(maxX, x);
    minY = Math.min(minY, y);
    maxY = Math.max(maxY, y);
  });
  return { ring, minX, maxX, minY, maxY };
});

const isLand = (lon, lat) => {
  let inside = false;
  for (const { ring, minX, maxX, minY, maxY } of boxed) {
    if (lon < minX || lon > maxX || lat < minY || lat > maxY) continue;
    for (let i = 0, j = ring.length - 1; i < ring.length; j = i++) {
      const [xi, yi] = ring[i];
      const [xj, yj] = ring[j];
      if (yi > lat !== yj > lat && lon < ((xj - xi) * (lat - yi)) / (yj - yi) + xi) inside = !inside;
    }
  }
  return inside;
};

const rows = [];
let dots = 0;
for (let lat = LAT_MAX - STEP / 2; lat > LAT_MIN; lat -= STEP) {
  let row = "";
  for (let lon = LON_MIN + STEP / 2; lon < LON_MAX; lon += STEP) {
    const land = isLand(lon, lat);
    if (land) dots += 1;
    row += land ? "#" : ".";
  }
  rows.push(row);
}

const out = `/**
 * GENERATED by scripts/generate-world-dots.mjs — do not edit by hand.
 * Dot-matrix land mask derived from Natural Earth 1:110m land (public domain).
 * Each row is one band of latitude, north to south; "#" marks a land cell.
 */
export const WORLD_GRID = {
  step: ${STEP},
  lonMin: ${LON_MIN},
  latMax: ${LAT_MAX},
  rows: [
${rows.map((row) => `    "${row}",`).join("\n")}
  ],
} as const;
`;

const target = resolve(dirname(fileURLToPath(import.meta.url)), "../src/lib/geo/world-dots.ts");
mkdirSync(dirname(target), { recursive: true });
writeFileSync(target, out);
console.log(`Wrote ${rows.length} rows × ${rows[0].length} cols, ${dots} land dots → ${target}`);
console.log(rows.join("\n"));
